type ColorMap = Mapping[int, int]


def _task_colors(task: Task | None) -> frozenset[int]:
    """Every color a grid of `task` holds."""
    if task is None:
        return frozenset()
    return colors([as_grid(g) for ex in [*task.train, *task.test]
                   for g in (ex.input, ex.output)])


def _recolored(p: Parameter, rows: list[Row], to: ColorMap) -> list[Row]:
    """`rows`, stored facts of `p`, with each `Color` column taken by `to`."""
    cols = set(color_columns(p))

    def value(i: int, v: Value) -> Value:
        return to.get(v, v) if i in cols and isinstance(v, int) else v

    return [tuple(value(i, v) for i, v in enumerate(r)) for r in rows]


def _complement(p: Parameter) -> GridValue | None:
    """The cells of `p`'s one `GRID_MASK` call complemented within its
    grid; None where `p` is stored by no such call."""
    match p.stored:
        case StoredGrid(grids=(call,)) if call.layout.form is GridForm.MASK:
            grid = tuple(tuple(0 if c == 1 else 1 for c in row)
                         for row in call.cells)
            return GridValue(call.keys, grid, call.anchor)
        case _:
            return None


def _reader_name(solver: Solver, p: Parameter) -> str:
    """The name the solver file reads `p` by: for a RIGID chart, the placed
    relation the block declares with it, since the chart's own name is
    generated by the expansion."""
    decl = declaration_of(solver.program, p)
    if decl.chart_of is None:
        return p.name
    return next(q.name for q in solver.params.parameters
                if (d := declaration_of(solver.program, q)).span == decl.span
                and d.chart_of is None)


FRAMED = frozenset({POSITION, BOX})
"""The column types that stay as stored under D4 in a parameter that is no
grid, since no frame is given for them."""


def _d4_images(solver: Solver, runs: Runs, stored: Mapping[str, list[Row]]
               ) -> list[tuple[D4Image, dict[str, Variation]]] | RunFailure:
    """Each D4 element's image of every stored parameter outside a RIGID
    block at once, by the transform a RIGID block places its charts by
    (`engine.Engine.d4_images`); the failure of the run that computes an
    image where it fails."""
    engine = runs.engine
    lib = checkout.programs() / LIB_FILE
    moved = [p for p in solver.params.parameters if stored[p.name]
             and (decl := declaration_of(solver.program, p)).chart_of is None
             and not solver.program.rigid_bound(decl)]

    def images(p: Parameter) -> RunResult:
        types = [c.type for c in p.columns]
        kept = frozenset() if isinstance(p.stored, StoredGrid) else \
            frozenset(i for i, t in enumerate(types) if t.text in FRAMED)
        program = engine.d4_images(lib, types, kept)
        if isinstance(program, ParseFailure):
            raise ValueError(f"`{p.name}`: no D4 image program: {program}")
        return engine.run(program, {D4_SOURCE: tuple(stored[p.name])},
                          [D4_IMAGE], runs.limits)

    by_element: dict[D4, dict[str, Variation]] = {d: {} for d in D4}
    for p, got in zip(moved, at_once(images, moved), strict=True):
        if not isinstance(got, Tuples):
            return got
        rows = stored[p.name]
        for d in D4:
            code = solver.lib.constants[f"D4_{d.value}"]
            image = [r[1:] for r in got.relations[D4_IMAGE] if r[0] == code]
            if set(image) != set(rows):
                by_element[d][p.name] = FixParam(p.name, tuple(image))
    return [(D4Image(d), changed) for d, changed in by_element.items()
            if changed]


def _relabelings(solver: Solver, runs: Runs
                 ) -> list[tuple[Relabeling, Where, dict[str, Variation]]] | RunFailure:
    """Each relabeling tried, where its finding stands, and the variation
    of each parameter it changes; a relabeling that changes no stored fact
    is left out; the failure of a run that computes a D4 image where it
    fails."""
    engine = runs.engine
    stored = {p.name: stored_facts(engine, solver, p)
              for p in solver.params.parameters}
    held = stored_colors(engine, solver, runs.cases_or_none)
    used = held | _task_colors(solver.task)
    free = next((c for c in COLORS if c not in used), None)
    maps: list[tuple[Relabeling, ColorMap]] = []
    ordered = sorted(held)
    if free is not None:
        maps += [(ColorSwap(c, free), {c: free, free: c}) for c in ordered]
    if len(ordered) > 1:
        maps.append((ColorCycle(tuple(ordered)),
                     dict(zip(ordered, [*ordered[1:], ordered[0]]))))
    out: list[tuple[Relabeling, Where, dict[str, Variation]]] = []
    for r, to in maps:
        changed: dict[str, Variation] = {}
        for p in solver.params.parameters:
            rows = stored[p.name]
            got = _recolored(p, rows, to)
            if set(got) != set(rows):
                changed[p.name] = FixParam(p.name, tuple(got))
        if changed:
            out.append((r, AtFile(WholeFile.SOLVER), changed))
    for p in solver.params.parameters:
        grid = _complement(p)
        if grid is not None:
            shown = _reader_name(solver, p)
            out.append((Complement(shown), AtParameter(shown),
                        {p.name: FixGrid(p.name, grid)}))
    images = _d4_images(solver, runs, stored)
    if not isinstance(images, list):
        return images
    out += [(r, AtFile(WholeFile.SOLVER), changed) for r, changed in images]
    return out


@quotes("principles.md", "Invariance",
        "What a group element changes is task data.")
def check_relabelings(solver: Solver, runs: Runs) -> list[Finding]:
    """Each relabeling (`_relabelings`) under which each case that reads a
    parameter it changes (`solver.dependence.Dependence.reads_parameter`)
    gives on each input the outcome it gives at the stored values, where
    at least one case reads one; the inputs are those of the open-values
    check less each witness entry whose `assign` gives a changed parameter
    (`checker.open_values.inputs_without`). A run that gives no result is
    its finding. Where the stored program fails a train pair, the check
    does not run, and its one finding says so."""
    train = runs.train_profile
    if isinstance(train, TimedOut):
        return [train.finding]
    if isinstance(train, Fails):
        return [Finding(Kind.RELABELINGS_UNCHECKED, AtFile(WholeFile.SOLVER),
                        TrainFails())]
    cases = runs.cases
    if not isinstance(cases, tuple):
        return [no_result(cases, RunKind.CASE, None, AtFile(WholeFile.SOLVER))]
    read = dependence(runs.engine, solver, bases_of(cases))
    params = {p.name: p for p in solver.params.parameters}
    tried = _relabelings(solver, runs)
    if not isinstance(tried, list):
        return [no_result(tried, RunKind.RELABELING, None,
                          AtFile(WholeFile.SOLVER))]

    def judge(item: tuple[Relabeling, Where, dict[str, Variation]]
              ) -> Finding | None:
        relabeling, where, changed = item
        reading = [c for c in cases
                   if any(read.reads_parameter(c.base, n) for n in changed)]
        if not reading:
            return None
        inputs = inputs_without(solver, runs, changed)
        variant = solver
        for v in changed.values():
            variant = with_program(variant, variation(runs.engine, variant, v))
        # A relabeling most often changes the first input's outcome, so
        # that input runs alone before the others.
        for part in (inputs[:1], inputs[1:]):
            before = runs.outcomes_on(solver, reading, part)
            after = runs.outcomes_on(variant, reading, part)
            failed = first_failure(o for got in after for o in got.values())
            if failed is not None:
                return no_result(failed, RunKind.RELABELING, None, where)
            if before != after:
                return None
        return Finding(Kind.UNOBSERVED_RELABELING, where,
                       UnobservedPayload(relabeling, tuple(
                           _reader_name(solver, params[n]) for n in changed)))

    return [f for f in at_once(judge, tried) if f is not None]
